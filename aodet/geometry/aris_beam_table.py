_BEAM_CENTERS = np.array([t[0] for t in BEAM_WIDTHS_ARIS3000_128])
_COLS = np.arange(128, dtype=float)


def beam_center_deg(col):
    """Beam center angle (deg) for column ``col`` (0..127, fractional ok)."""
    return np.interp(np.asarray(col, dtype=float), _COLS, _BEAM_CENTERS)


def col_of_angle(deg):
    """Fractional beam column imaging fan angle ``deg``."""
    return np.interp(np.asarray(deg, dtype=float), _BEAM_CENTERS, _COLS)


def row_of_range(rng, window_start, sample_period_us, soundspeed):
    """Image row imaging slant range ``rng`` (two-way travel)."""
    dr = sample_period_us * 1e-6 * soundspeed / 2.0
    return (rng - window_start) / dr


def range_of_row(row, window_start, sample_period_us, soundspeed):
    """Slant range imaged at ``row``."""
    dr = sample_period_us * 1e-6 * soundspeed / 2.0
    return window_start + row * dr


def fan_halfwidth_deg():
    return float(max(abs(_BEAM_CENTERS[0]), abs(_BEAM_CENTERS[-1])))
